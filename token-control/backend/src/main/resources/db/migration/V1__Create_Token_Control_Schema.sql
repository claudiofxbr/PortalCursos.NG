-- Uma linha por mensagem do assistente (usage de cada resposta). Só contagens e metadados — sem conteúdo.
CREATE TABLE token_usage_entries (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id            VARCHAR(128) NOT NULL,
    occurred_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    hour_bucket           TIMESTAMP WITH TIME ZONE NOT NULL,
    session_id            VARCHAR(64),
    process               VARCHAR(120) NOT NULL,
    model                 VARCHAR(80)  NOT NULL,
    input_tokens          BIGINT NOT NULL DEFAULT 0,
    output_tokens         BIGINT NOT NULL DEFAULT 0,
    cache_creation_tokens BIGINT NOT NULL DEFAULT 0,
    cache_read_tokens     BIGINT NOT NULL DEFAULT 0,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_usage_message UNIQUE (message_id),
    CONSTRAINT ck_usage_non_negative CHECK (
        input_tokens >= 0 AND output_tokens >= 0 AND cache_creation_tokens >= 0 AND cache_read_tokens >= 0)
);

CREATE INDEX idx_usage_occurred_at ON token_usage_entries (occurred_at);
CREATE INDEX idx_usage_process_occurred ON token_usage_entries (process, occurred_at);
