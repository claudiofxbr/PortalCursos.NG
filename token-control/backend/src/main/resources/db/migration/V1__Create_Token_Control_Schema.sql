-- Configuração única do plano (linha id=1): quando o ciclo semanal reseta e qual o orçamento.
CREATE TABLE token_plan_config (
    id                  SMALLINT PRIMARY KEY,
    plan_name           VARCHAR(40)  NOT NULL,
    reset_day_of_week   SMALLINT     NOT NULL,
    reset_time          TIME         NOT NULL,
    timezone            VARCHAR(60)  NOT NULL,
    weekly_limit_tokens BIGINT       NOT NULL,
    count_cache_reads   BOOLEAN      NOT NULL DEFAULT FALSE,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_plan_config_singleton CHECK (id = 1),
    CONSTRAINT ck_plan_config_day CHECK (reset_day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_plan_config_limit CHECK (weekly_limit_tokens > 0)
);

